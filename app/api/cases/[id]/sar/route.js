import { NextResponse } from 'next/server';
import { query } from '@/lib/db';
import { getServerSession } from 'next-auth';
import { authOptions } from '@/lib/auth';
import { generateSARContent } from '@/lib/gemini';

export async function GET(req, { params }) {
  const session = await getServerSession(authOptions);
  if (!session) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });

  const { id } = await params;

  const caseResult = await query(
    `SELECT c.*, r.fraud_type, r.severity, r.urgency, r.department, r.amount,
            r.regulatory_flag, r.ai_summary, r.created_at as report_date, r.description
     FROM cases c JOIN reports r ON c.report_id = r.id WHERE c.id = $1`, [id]
  );
  if (caseResult.rows.length === 0) return NextResponse.json({ error: 'Not found' }, { status: 404 });

  const caseData = caseResult.rows[0];
  const evidenceResult = await query('SELECT * FROM evidence WHERE case_id = $1', [id]);

  let sarData;
  try {
    sarData = await generateSARContent(caseData, caseData, evidenceResult.rows);
  } catch {
    sarData = {
      sar_number: `SAR-${Date.now()}`,
      filing_date: new Date().toISOString().split('T')[0],
      subject_entity: 'Internal Employee / Unknown',
      activity_type: caseData.fraud_type?.replace(/_/g, ' ') || 'Fraud',
      date_of_activity: new Date(caseData.report_date).toLocaleDateString('en-IN'),
      amount_involved: caseData.amount ? `₹${Number(caseData.amount).toLocaleString('en-IN')}` : 'Undetermined',
      description: caseData.description?.substring(0, 300) || 'See case file',
      basis_for_suspicion: caseData.ai_summary || 'Whistleblower report received and triaged.',
      evidence_summary: `${evidenceResult.rows.length} evidence items on file.`,
      recommended_action: 'Refer to legal counsel and regulatory authority.',
      regulatory_references: ['SEBI (LODR) Regulations 2015', 'PMLA 2002'],
    };
  }

  // Build PDF as plain text (no external PDF library needed)
  const pdfContent = buildSARText(sarData, caseData, id);

  return new NextResponse(pdfContent, {
    headers: {
      'Content-Type': 'text/plain',
      'Content-Disposition': `attachment; filename="SAR-Case-${id}-${sarData.sar_number}.txt"`,
    },
  });
}

function buildSARText(sar, caseData, caseId) {
  const line = '─'.repeat(70);
  const dline = '═'.repeat(70);

  return `
${dline}
          SUSPICIOUS ACTIVITY REPORT (SAR)
          FraudWatch360 Investigation Platform
${dline}

SAR Reference Number : ${sar.sar_number}
Filing Date          : ${sar.filing_date}
Case ID              : #${caseId}
Classification       : ${caseData.severity?.toUpperCase()} SEVERITY
Regulatory Flag      : ${caseData.regulatory_flag ? 'YES — IMMEDIATE REPORTING REQUIRED' : 'No'}

${line}
SECTION 1 — SUBJECT INFORMATION
${line}

Subject Entity       : ${sar.subject_entity}
Department           : ${caseData.department || 'Unknown'}
Activity Type        : ${sar.activity_type}
Date of Activity     : ${sar.date_of_activity}
Amount Involved      : ${sar.amount_involved}

${line}
SECTION 2 — DESCRIPTION OF SUSPICIOUS ACTIVITY
${line}

${sar.description}

${line}
SECTION 3 — BASIS FOR SUSPICION
${line}

${sar.basis_for_suspicion}

${line}
SECTION 4 — EVIDENCE SUMMARY
${line}

${sar.evidence_summary}

${line}
SECTION 5 — AI TRIAGE SUMMARY (Gemini)
${line}

Fraud Type  : ${caseData.fraud_type?.replace(/_/g, ' ')}
Severity    : ${caseData.severity}
Urgency     : ${caseData.urgency}

${caseData.ai_summary || 'AI analysis not available.'}

${line}
SECTION 6 — RECOMMENDED ACTION
${line}

${sar.recommended_action}

${line}
SECTION 7 — REGULATORY REFERENCES
${line}

${(sar.regulatory_references || []).map((r, i) => `${i + 1}. ${r}`).join('\n')}

${dline}
CERTIFICATION

This Suspicious Activity Report has been generated by the FraudWatch360
platform based on an anonymous whistleblower submission. The contents are
based on AI-assisted analysis and investigator review.

This document is CONFIDENTIAL and subject to attorney-client privilege
where applicable. Unauthorized disclosure is prohibited.

Generated by : ${new Date().toLocaleString('en-IN')}
Platform     : FraudWatch360 v1.0
${dline}
`.trim();
}